// Taps through this chapter's interactives on a phone viewport and screenshots each state (dev server :5300).
import { chromium } from 'playwright';
const OUT = process.argv[2] || '/tmp';
const browser = await chromium.launch({ executablePath: process.env.HOME + '/.cache/ms-playwright/chromium-1248/chrome-linux64/chrome' });
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true, deviceScaleFactor: 1 });
const p = await ctx.newPage();
const errs = [];
p.on('pageerror', (e) => errs.push(e.message));
p.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
await p.goto('http://127.0.0.1:5300/talos-explained/bt-workflow.html', { waitUntil: 'networkidle' });
const shot = async (sel, name) => { const el = p.locator(sel).first(); await el.scrollIntoViewIfNeeded(); await p.waitForTimeout(400); await el.screenshot({ path: `${OUT}/i_${name}.png` }); };
await p.locator('.loop-steps button').nth(2).tap();
await shot('#loop-panel', 'loop3');
await p.locator('.pp .seg button').nth(2).tap();
await p.locator('.pp .presets button', { hasText: '-1' }).first().tap();
await shot('#ports-play', 'sub_minus1');
await p.locator('.pp .bb input').nth(2).tap();
await shot('#ports-play', 'sub_minus1_set');
await p.locator('.pp .seg button').nth(0).tap();
await p.locator('.pp .presets button', { hasText: 'ceiling' }).nth(2).tap();
await shot('#ports-play', 'in_literal');
await p.locator('.pp .seg button').nth(2).tap();
await p.locator('.pp .presets button', { hasText: '""' }).first().tap();
await shot('#ports-play', 'sub_empty');
await p.locator('.pp .bb input').nth(4).tap();
await shot('#ports-play', 'sub_empty_off');
await shot('#drift', 'drift_default');
await p.locator('#drift .seg button').nth(1).tap();
await p.locator('.drift-row', { hasText: 'CompTree' }).first().tap();
await shot('#drift', 'drift');
await p.locator('.mk-filter button', { hasText: 'Running' }).tap();
await p.locator('.mk-list li:not([hidden]) summary').nth(4).tap();
await shot('#mistakes-panel', 'mistakes');
await p.locator('#pipeline .node').nth(1).tap();
await shot('.panel:has(#pipeline)', 'pipeline');
console.log(errs.join('\n') || 'no errors');
await browser.close();
